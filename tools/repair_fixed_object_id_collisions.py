#!/usr/bin/env python3
"""Batch-repair historical fixed-object ID collisions using deterministic identity priority.

The collision report is generated by build_fixed_object_registry.py.  For the
historical duplicate class, two permanent IDs represent one physical object.
The survivor is selected by the same namespace priority used by the registry:
astrometric/catalog identifiers (HIP, HD, Gaia, WDS, ...) precede Bayer labels.
No object-specific exceptions are encoded here.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT_PATH = ROOT / "generated" / "fixed-object-identity-collisions.json"
MERGES_PATH = ROOT / "database" / "fixed-object-id-merges.json"

NAMESPACE_PRIORITY = {
    "hip": 0,
    "hd": 1,
    "gaia_dr3": 2,
    "wds": 3,
    "ngc": 4,
    "ic": 5,
    "sh2": 6,
    "bayer": 7,
    "variable_star": 8,
    "messier": 9,
    "caldwell": 10,
    "finest_ngc": 11,
    "special": 12,
    "component": 13,
}


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def identity_key(identity):
    return (
        NAMESPACE_PRIORITY.get(str(identity.get("namespace") or ""), 999),
        str(identity.get("namespace") or ""),
        str(identity.get("value") or ""),
    )


def main():
    if not REPORT_PATH.exists():
        raise SystemExit(f"Missing collision report: {REPORT_PATH}")

    report = load(REPORT_PATH)
    collisions = report.get("identity_collisions") or []
    split_collisions = report.get("split_collisions") or []

    if split_collisions:
        raise SystemExit("Batch repair refuses physical-identity splits; human review is required.")

    existing_payload = load(MERGES_PATH) if MERGES_PATH.exists() else {
        "schema_version": 1,
        "purpose": "Human-reviewed redirects for historical permanent fixed-object IDs that were later proven to identify the same physical object.",
        "merges": [],
    }
    existing = {
        int(item["retired_fixed_object_id"]): int(item["surviving_fixed_object_id"])
        for item in existing_payload.get("merges") or []
    }

    additions = []
    for collision in collisions:
        if collision.get("classification") != "likely_historical_duplicate_identity":
            raise SystemExit(
                "Batch repair encountered a non-historical collision class: "
                + repr(collision.get("classification"))
            )

        ids = [int(value) for value in collision.get("permanent_ids") or []]
        identities = collision.get("permanent_id_canonical_identities") or {}
        if len(ids) != 2:
            raise SystemExit(
                f"Batch repair requires exactly two IDs per historical duplicate; got {ids} "
                f"for provisional group {collision.get('provisional_group_id')}"
            )
        if any(str(fixed_id) not in identities for fixed_id in ids):
            raise SystemExit(f"Missing canonical identities for collision IDs {ids}")

        ranked = sorted(ids, key=lambda fixed_id: identity_key(identities[str(fixed_id)]))
        survivor, retired = ranked[0], ranked[1]
        survivor_ns = str(identities[str(survivor)].get("namespace") or "")
        retired_ns = str(identities[str(retired)].get("namespace") or "")

        if survivor_ns == retired_ns:
            raise SystemExit(f"Batch repair will not merge same-namespace identities: {ids}")

        prior = existing.get(retired)
        if prior is not None and prior != survivor:
            raise SystemExit(f"Conflicting existing merge for {retired}: {prior} vs {survivor}")

        if prior is None:
            additions.append({
                "retired_fixed_object_id": retired,
                "surviving_fixed_object_id": survivor,
                "reason": (
                    "Batch-resolved historical duplicate: permanent IDs "
                    f"{retired} ({retired_ns}) and {survivor} ({survivor_ns}) "
                    "refer to the same physical object; survivor selected by "
                    "the registry namespace priority."
                ),
            })
            existing[retired] = survivor

    additions.sort(key=lambda item: item["retired_fixed_object_id"])
    if additions:
        merges = list(existing_payload.get("merges") or []) + additions
        merges.sort(key=lambda item: int(item["retired_fixed_object_id"]))
        existing_payload["schema_version"] = 1
        existing_payload["merges"] = merges
        MERGES_PATH.write_text(
            json.dumps(existing_payload, indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )

    print(f"Batch collision repair resolved {len(additions)} new historical ID merges.")
    print(f"Total merge redirects: {len(existing_payload.get('merges') or [])}.")


if __name__ == "__main__":
    main()
